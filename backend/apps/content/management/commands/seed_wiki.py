class Command(BaseCommand):
    help = "Seed the wiki with realistic Persian content pages."

    def add_arguments(self, parser) -> None:
        parser.add_argument(
            "--relink",
            action="store_true",
            default=True,
            help="Run the auto-linker over the seeded pages (default).",
        )

    @transaction.atomic
    def handle(self, *args: object, **options: object) -> None:
        root = self._wiki_root()
        created = 0
        updated = 0

        for spec in PAGES:
            page = self._upsert_page(root, spec)
            if page is None:
                continue
            if page.pk and page.first_published_at is None:
                created += 1
            else:
                updated += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Seeded {len(PAGES)} wiki pages ({created} new, {updated} updated)."
            )
        )

        auto_created, auto_skipped = self._seed_auto_pages(root)
        if auto_created or auto_skipped:
            self.stdout.write(
                self.style.SUCCESS(
                    f"Generated {auto_created} spec-derived pages for parts without a "
                    f"written page ({auto_skipped} skipped: no specs)."
                )
            )

        if options.get("relink", True):
            self._relink()

    # --- helpers ------------------------------------------------------------

    def _wiki_root(self) -> Page:
        """The section page that holds every wiki page.

        The section lives under the **site root** (the page the default Wagtail
        site is rooted at), not under the tree root — otherwise Wagtail treats
        the pages as belonging to no site and the admin cannot manage them.
        """
        from apps.content.models import WikiPage

        # Look for the section by slug at any depth under the tree root.
        root = Page.objects.filter(slug=WIKI_ROOT_SLUG).first()
        if root:
            return root

        site_root = self._site_root()
        return site_root.add_child(instance=WikiPage(title="ویکی", slug=WIKI_ROOT_SLUG))

    def _site_root(self) -> Page:
        """The page the default site is rooted at."""
        from wagtail.models import Site

        site = Site.objects.filter(is_default_site=True).first() or Site.objects.first()
        if site is not None:
            return site.root_page

        # No site yet (a fresh database): fall back to the tree root's first
        # child, which is the conventional "home" page.
        tree_root = Page.get_first_root_node()
        if tree_root is None:
            raise RuntimeError("the Wagtail page tree has no root node")
        return tree_root.get_children().first() or tree_root

    def _upsert_page(self, root: Page, spec: dict) -> WikiPage | None:
        from apps.content.models import BuyerGuidePage, ComponentPage, ConceptPage

        model = {
            "component": ComponentPage,
            "guide": BuyerGuidePage,
            "concept": ConceptPage,
        }[spec["type"]]

        entity = None
        if spec.get("entity"):
            entity = Entity.objects.filter(slug=spec["entity"]).first()
            if entity is None:
                self.stderr.write(
                    self.style.WARNING(
                        f"unknown entity {spec['entity']!r} for page {spec['slug']!r}"
                    )
                )
                return None

        existing = root.get_children().filter(slug=spec["slug"]).first()
        if existing is None:
            # `add_child` copies the instance into the tree; the original
            # object stays unsaved, so work on the stored copy.
            root.add_child(instance=model(title=spec["title"], slug=spec["slug"]))
            page = cast("WikiPage", root.get_children().get(slug=spec["slug"]).specific)
        else:
            # The page may have been created as another type; rebuild it.
            page = cast("WikiPage", existing.specific)

        # Product-bound wiki articles use the same complete display name as
        # the catalog, so the title, card and entity badge cannot disagree.
        page.title = (
            entity.display_title if spec["type"] == "component" and entity else spec["title"]
        )
        page.summary = spec["summary"]
        page.entity = entity
        page.review_by = timezone.localdate() + timedelta(days=spec.get("review_days", 90))
        page.tags = spec.get("tags", [])
        # The body and the guide fields live on the concrete page type.
        concrete = cast("Any", page)
        body_blocks = list(spec.get("body", []))
        if spec["type"] == "guide":
            # Naming the recommended systems in the body is what makes them
            # *linked*: the auto-linker only sees text. Without this the guide
            # listed SKUs the reader could not click, and the systems stayed
            # orphan pages.
            recommended = list(Product.objects.filter(sku__in=spec.get("products", [])))
            if recommended:
                body_blocks.append(("heading", "h2", "سیستم‌های پیشنهادی این راهنما"))
                body_blocks.append(("list", "ul", [item.display_title for item in recommended]))
        concrete.body = self._build_body(body_blocks)

        # Every field must be set *before* the revision is published, or the
        # published revision keeps the old (empty) values.
        if spec["type"] == "guide" and entity is None:
            products = Product.objects.filter(sku__in=spec.get("products", []))
            concrete.recommended_products.set(products)
            concrete.use_case = spec.get("use_case", "")
            concrete.resolution = spec.get("resolution", "")
            if spec.get("budget_max"):
                from decimal import Decimal

                concrete.budget_max = Decimal(spec["budget_max"])

        page.save_revision().publish()
        # The guide's product list is a many-to-many on the revision, so it
        # has to be written after the page has a primary key.
        if spec["type"] == "guide" and entity is None:
            products = Product.objects.filter(sku__in=spec.get("products", []))
            concrete.recommended_products.set(products)
            page.save_revision().publish()

        return page

    def _seed_auto_pages(self, root: Page) -> tuple[int, int]:
        """Give every published hardware part a page, built from its own specs.

        A hand-written `PAGES` entry always wins. A part without one gets a page
        whose body is *only* its catalog data (its own summary plus a spec table)
        — nothing is invented, and no product is left without a wiki article, so
        the product ↔ page link is complete for every part.
        """
        covered = {spec["entity"] for spec in PAGES if spec.get("entity")}
        types = [
            EntityType.CPU,
            EntityType.MOTHERBOARD,
            EntityType.RAM,
            EntityType.GPU,
            EntityType.PSU,
            EntityType.CASE,
            EntityType.COOLER,
            EntityType.STORAGE,
            EntityType.PREBUILT,
        ]
        created = 0
        skipped = 0
        queryset = (
            Entity.objects.filter(status=EntityStatus.PUBLISHED, type__in=types)
            .exclude(slug__in=covered)
            .order_by("type", "slug")
        )
        for entity in queryset:
            rows = self._spec_rows(entity)
            if not rows:
                # No specs at all means an empty page: report it, never invent it.
                skipped += 1
                self.stderr.write(
                    self.style.WARNING(f"no specs to build a page for {entity.slug!r}")
                )
                continue
            if self._upsert_page(root, self._auto_spec(entity, rows)) is not None:
                created += 1
        return created, skipped

    def _auto_spec(self, entity: Entity, rows: list[tuple[str, str]]) -> dict:
        summary = entity.summary_fa or entity.summary or entity.title
        body: list[tuple] = [
            ("paragraph", summary),
            ("heading", "h2", "مشخصات کلیدی"),
            ("spec_table", "", rows),
        ]
        if entity.type == EntityType.PREBUILT:
            parts = self._prebuilt_part_names(entity)
            if parts:
                # Naming the parts is what links them: the auto-linker reads text.
                body.append(("heading", "h2", "قطعات این سیستم"))
                body.append(("list", "ul", parts))
        body.append(
            (
                "callout",
                "info",
                "منبع این صفحه",
                "این صفحه از دادهٔ کاتالوگ همین قطعه ساخته شده است و ادعای "
                "اضافه‌ای ندارد؛ متن تحریریه پس از بازبینی جایگزین می‌شود.",
            )
        )
        return {
            "slug": entity.slug,
            "title": entity.title,
            "summary": summary,
            "entity": entity.slug,
            "type": "component",
            "review_days": 90,
            "body": body,
        }

    def _prebuilt_part_names(self, entity: Entity) -> list[str]:
        """The names of the parts a prebuilt ships with, for its page body."""
        spec = getattr(entity, "spec", None)
        slugs = (spec.common or {}).get("components") if spec else None
        if not slugs:
            return []
        by_slug = {item.slug: item for item in Entity.objects.filter(slug__in=slugs)}
        return [by_slug[slug].title for slug in slugs if slug in by_slug]

    def _spec_rows(self, entity: Entity) -> list[tuple[str, str]]:
        """(label, value) rows for the entity's own specs, in Persian."""
        from apps.linking.api import SPEC_LABELS

        spec = getattr(entity, "spec", None)
        if spec is None:
            return []
        merged = {**(spec.common or {}), **(spec.extra or {})}
        rows: list[tuple[str, str]] = []
        for key, value in merged.items():
            if key.endswith("_fa") or key in {"components", "useful_links"}:
                continue
            label = SPEC_LABELS.get(key, key.replace("_", " "))
            rows.append((label, self._format_spec(value)))
        return rows

    def _format_spec(self, value: Any) -> str:
        if isinstance(value, bool):
            return "بله" if value else "خیر"
        if isinstance(value, (list, tuple)):
            return "، ".join(str(item) for item in value)
        return str(value)

    def _build_body(self, blocks: list[tuple]) -> Any:
        """Turn the compact tuple format into StreamField child blocks."""
        from apps.content.blocks import BodyBlock

        stream = []
        for item in blocks:
            kind = item[0]
            if kind == "heading":
                _, level, text = item
                stream.append(("heading", {"level": level, "text": text}))
            elif kind == "paragraph":
                stream.append(("paragraph", item[1]))
            elif kind == "spec_table":
                _, title, rows = item
                stream.append(
                    (
                        "spec_table",
                        {
                            "title": title,
                            "rows": [{"label": label, "value": value} for label, value in rows],
                        },
                    )
                )
            elif kind == "callout":
                _, ckind, title, text = item
                stream.append(("callout", {"kind": ckind, "title": title, "text": text}))
            elif kind == "list":
                _, style, items = item
                stream.append(("list", {"style": style, "items": items}))
            else:
                continue
        return BodyBlock().to_python(stream)

    def _relink(self) -> None:
        """Run the auto-linker over every seeded page."""
        from apps.content.models import WikiPage

        created = 0
        red = 0
        for page in WikiPage.objects.live().select_related("entity"):
            result = link_page(page)
            created += len(result.created)
            red += len(result.red_links)
        self.stdout.write(
            self.style.SUCCESS(f"Auto-linked pages: {created} links created, {red} red links.")
        )
